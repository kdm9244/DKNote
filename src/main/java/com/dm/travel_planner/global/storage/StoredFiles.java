package com.dm.travel_planner.global.storage;

import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.*;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Component;
import org.springframework.transaction.support.*;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;
import software.amazon.awssdk.services.s3.model.S3Exception;
import java.io.*;
import java.nio.file.*;
import java.util.UUID;

/** References are generated by the server and persisted only after ownership checks. */
@Slf4j @Component
public class StoredFiles {
    public enum Area { LEARNING, CHECKLIST }
    private final String provider;
    private final ObjectProvider<R2Storage> r2;
    private final Path learning, checklist;
    public StoredFiles(@Value("${app.storage.provider:local}") String provider, ObjectProvider<R2Storage> r2,
                       @Value("${app.upload.learning-dir:./.local/learning-files}") String learning,
                       @Value("${app.upload.checklist-dir:./uploads/checklist}") String checklist) {
        if (!provider.equals("local") && !provider.equals("r2")) throw new IllegalStateException("FILE_STORAGE_PROVIDER는 local 또는 r2여야 합니다.");
        this.provider=provider; this.r2=r2;
        this.learning=Path.of(learning).toAbsolutePath().normalize();
        this.checklist=Path.of(checklist).toAbsolutePath().normalize();
    }

    public String upload(Area area, MultipartFile file) {
        if(file.isEmpty() || file.getSize()>20L*1024*1024)
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST,"파일은 20MB 이하로 업로드하세요.");
        try(var input=file.getInputStream()) { return store(area,input,file.getSize(),file.getContentType()); }
        catch(IOException ex) { throw unavailable(); }
    }

    public String store(Area area, InputStream input, long size, String type) {
        if(!TransactionSynchronizationManager.isActualTransactionActive())
            throw new IllegalStateException("파일 업로드에는 DB 트랜잭션이 필요합니다.");
        String key=area.name().toLowerCase(java.util.Locale.ROOT)+"/"+UUID.randomUUID();
        String ref=provider+"://"+key;
        // Register before the write, so a partially failed write is also cleaned up on rollback.
        if(TransactionSynchronizationManager.isSynchronizationActive())
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override public void afterCompletion(int status) {
                    if(status==STATUS_ROLLED_BACK) quietlyDelete(area,ref);
                    else if(status!=STATUS_COMMITTED) log.warn("DB 커밋 상태 불명: 파일 보존, reference={}",ref);
                }
            });
        try {
            if(provider.equals("r2")) remote().put(key,input,size,type);
            else { Path target=localPath(area,key); Files.createDirectories(target.getParent()); Files.copy(input,target); }
            return ref;
        } catch(Exception ex) { quietlyDelete(area,ref); throw unavailable(); }
    }

    public Resource resource(Area area, String ref) {
        try {
            if(ref.startsWith("r2://")) return remote().resource(key(area,ref));
            Path path=existingLocal(area,ref);
            if(!Files.isRegularFile(path)) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"저장된 파일을 찾을 수 없습니다.");
            return new FileSystemResource(path);
        } catch(S3Exception ex) {
            if(ex.statusCode()==404) throw new ResponseStatusException(HttpStatus.NOT_FOUND,"저장된 파일을 찾을 수 없습니다.");
            throw unavailable();
        } catch(ResponseStatusException ex) { throw ex; }
        catch(RuntimeException ex) { throw unavailable(); }
    }

    public void deleteAfterCommit(Area area,String ref) {
        if(!TransactionSynchronizationManager.isSynchronizationActive()) throw new IllegalStateException("파일 삭제는 DB 트랜잭션 안에서 요청해야 합니다.");
        TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
            @Override public void afterCommit() { quietlyDelete(area,ref); }
        });
    }

    private void quietlyDelete(Area area,String ref) {
        try {
            if(ref.startsWith("r2://")) remote().delete(key(area,ref));
            else Files.deleteIfExists(existingLocal(area,ref));
        } catch(Exception ex) { log.warn("파일 정리 실패: area={}, reference={} (재정리 필요)",area,ref); }
    }
    private R2Storage remote() {
        R2Storage storage=r2.getIfAvailable();
        if(storage==null) throw unavailable();
        return storage;
    }
    private String key(Area area,String ref) {
        String key=ref.substring(ref.indexOf("://")+3);
        if(!key.matches(area.name().toLowerCase(java.util.Locale.ROOT)+"/[a-f0-9-]{36}"))
            throw new ResponseStatusException(HttpStatus.NOT_FOUND,"잘못된 파일 참조입니다.");
        return key;
    }
    private Path localPath(Area area,String key) {
        Path root=area==Area.LEARNING?learning:checklist;
        Path path=root.resolve(key.substring(key.indexOf('/')+1)).normalize();
        if(!path.startsWith(root)) throw new IllegalArgumentException("Invalid storage path");
        return path;
    }
    private Path existingLocal(Area area,String ref) {
        if(ref.startsWith("local://")) return localPath(area,key(area,ref));
        // Legacy records used a PDF basename or /uploads/checklist/<basename>.
        String name=ref.replace('\\','/'); name=name.substring(name.lastIndexOf('/')+1);
        if(name.isBlank() || name.equals(".") || name.equals("..") || name.indexOf(':')>=0)
            throw new ResponseStatusException(HttpStatus.NOT_FOUND);
        Path result=localPath(area,"legacy/"+name);
        if(area==Area.CHECKLIST && !Files.isRegularFile(result)) {
            Path legacy=Path.of("uploads","checklist").toAbsolutePath().normalize();
            Path fallback=legacy.resolve(name).normalize();
            if(fallback.startsWith(legacy) && Files.isRegularFile(fallback)) return fallback;
        }
        return result;
    }
    private ResponseStatusException unavailable() { return new ResponseStatusException(HttpStatus.SERVICE_UNAVAILABLE,"파일 저장소에 연결할 수 없습니다. 잠시 후 다시 시도하세요."); }
}
